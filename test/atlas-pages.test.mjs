// test/atlas-pages.test.mjs —— atlas 页名解析（parseAtlasPages）
//
// 锁的核心回归：**带 BOM 的 atlas 首行必须被识别为第一页**。
//   根因：JS 的 \s **包含 U+FEFF**，而 AssetStudio 导出的 atlas 首行是「BOM + 页名」，
//   `/^[^\s]/` 会把首行判成"有前导空白"而整行跳过 ⇒ 多页图集第一页页名丢失
//   （现场：NIKKE 根 247 个模型里 34 份 atlas 带 BOM，均丢第一页 ⇒ 画面空白）。
// 三份"同口径"实现的差异（别再改回去）：
//   · 服务端 probe.mjs        —— 读文件后**先剥 BOM**再按行匹配
//   · 插件 unity-spine-bundle —— 读内存文本后**先剥 BOM**（同口径）
//   · 前端 engine/textures.js —— 先 `trim()` 再匹配，trim 会吃掉 U+FEFF ⇒ 天然免疫（不需要改）
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { parseAtlasPages } from '../src/server/assets/probe.mjs';

/** 写一个临时 atlas 文件并解析；自动清理 */
function parseText(text, encoding = 'utf8') {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'atlas-pages-'));
  const file = path.join(dir, 'x.atlas');
  try {
    fs.writeFileSync(file, text, encoding);
    return parseAtlasPages(file);
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

const TWO_PAGES = [
  'size: 2048,2048',
  'format: RGBA8888',
  'filter: Linear,Linear',
  'repeat: none',
  'body',
  '  rotate: false',
  '  bounds: 0,0,100,100',
  '',
  'size: 1024,1024',
  'format: RGBA8888',
  'filter: Linear,Linear',
  'repeat: none',
  'head',
  '  bounds: 0,0,50,50',
  '',
].join('\n');

test('带 BOM 的首行必须被识别为第一页（NIKKE 现场根因）', () => {
  const text = `\uFEFFc010_00.png\n${TWO_PAGES}c010_00_2.png\n`;
  const pages = parseText(text);
  assert.deepEqual(pages, ['c010_00.png', 'c010_00_2.png']);
  assert.equal(pages[0], 'c010_00.png', '第一页不能丢');
});

test('不带 BOM 的双页 atlas 行为不变（回归）', () => {
  const text = `c010_00.png\n${TWO_PAGES}c010_00_2.png\n`;
  assert.deepEqual(parseText(text), ['c010_00.png', 'c010_00_2.png']);
});

test('CRLF 换行：页名不带 \\r（trim 仍生效）', () => {
  const text = `\uFEFFc010_00.png\r\n${TWO_PAGES.replace(/\n/g, '\r\n')}c010_00_2.png\r\n`;
  const pages = parseText(text);
  assert.deepEqual(pages, ['c010_00.png', 'c010_00_2.png']);
  assert.ok(pages.every((p) => !p.includes('\r')), '页名里不能残留 \\r');
});

test('缩进行（区域/属性）即使以 .png 结尾也不算页头', () => {
  // 规则：页头必须**未缩进**；缩进行是区域名或属性
  const text = '\uFEFFreal_page.png\n  fake_indented.png\n  bounds: 0,0,1,1\n';
  assert.deepEqual(parseText(text), ['real_page.png']);
});

test('不以图片扩展名结尾的行不被误吞（注释 / 属性 / 区域名）', () => {
  const text = [
    '\uFEFFc010_00.png',
    '// generated by AssetStudio',
    'size: 2048,2048',
    'body',
    '  bounds: 0,0,100,100',
    '  offsets: 1,2,3,4',
    'c010_00_2.jpg',
    '',
  ].join('\n');
  assert.deepEqual(parseText(text), ['c010_00.png', 'c010_00_2.jpg'], 'jpg 也要认，注释/属性不能认');
});

test('只有 BOM 没有页名 ⇒ 空数组（不抛错）', () => {
  assert.deepEqual(parseText('\uFEFF\n'), []);
});

test('文件不存在 ⇒ 空数组（既有兜底不变）', () => {
  assert.deepEqual(parseAtlasPages('/no/such/file.atlas'), []);
});
